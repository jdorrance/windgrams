import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { DEFAULT_STYLESHEET } from '@azohra/meteo.briefing/meteogram';

const source = new URL('../src/', import.meta.url);
const chart = readFileSync(new URL('styles/windgram.css', source), 'utf8');
const diagnostics = DEFAULT_STYLESHEET + readFileSync(new URL('styles/diagnostics.css', source), 'utf8');
const generated = new URL('generated/', source);
mkdirSync(generated, { recursive: true });
// Both delivery forms derive from the same CSS files; browsers never read files at runtime.
writeFileSync(new URL('styles.ts', generated), `// Generated by scripts/build-styles.mjs. Edit src/styles/*.css.\nexport const chartStyles = ${JSON.stringify(chart)};\nexport const diagnosticStyles = ${JSON.stringify(diagnostics)};\n`);
const stylesheet = `${chart}\n${diagnostics}\n`;
writeFileSync(new URL('styles.css', generated), stylesheet);
